function write(root = path.resolve(__dirname, '../doc/requirements')) {
  const outputs = [];
  for (const [type, file] of [['main','需求说明.md'],['sub','子页面与操作细化.md']]) {
    const target = path.join(root, '28-数据安全检测', file);
    const before = fs.readFileSync(target, 'utf8');
    const after = renderDocumentFixed(type, before);
    outputs.push({ target, before, after });
  }
  let changed = 0;
  for (const output of outputs) {
    if (output.after !== output.before) { fs.writeFileSync(output.target, output.after); changed += 1; }
  }
  return { changed, requirements: MAIN.length + SUB.length, acceptance: 144, nfr: NFR.length };
}

