function cell(x) { return String(x ?? '').replaceAll('|','&#124;').replaceAll('\n','<br>'); }
function mdTable(headers, rows) { return ['| '+headers.join(' | ')+' |','|'+headers.map(()=> '---').join('|')+'|',...rows.map(r=>'| '+r.map(cell).join(' | ')+' |'),''].join('\n'); }
function nfrRows(ids) { return NFR.filter(x=>ids.includes(x[0])).map(([id,name,target])=>[id+'：'+name,target,'未执行']); }
function requestDescription(method,url,input) {
  const keys=[...url.matchAll(/\{([^}]+)\}/g)].map(x=>x[1]);
  const path=keys.length?'路径参数 '+keys.join('、'):'',value=String(input||'');
  if(value==='无body') return path||'无body';
  if(method==='GET'&&keys.length&&/(?:方案|任务|报告|记录)?ID/.test(value)&&!value.includes('{')) return path;
  if(method==='DELETE'&&keys.length) return path+'；无body';
  if(method==='GET') return [path,'GET query '+value].filter(Boolean).join('；');
  return [path,value.includes('body')?'JSON '+value:'JSON body '+value].filter(Boolean).join('；');
}

