function guardDocument(type,text) {
  const source=registry[type], expected=source.entries.map(x=>x.id);
  const requirements=[...text.matchAll(/^### (DSTS-\d{3})\b/gm)].map(x=>x[1]);
  if(JSON.stringify(requirements)!==JSON.stringify(expected)) throw new Error('DSTS requirement IDs missing, duplicated or reordered: '+type);
  const acceptance=[...text.matchAll(/^\| (DSTS-AC-\d{3}) \|.*$/gm)];
  if(JSON.stringify(acceptance.map(x=>x[1]))!==JSON.stringify(source.acceptance.map(x=>x.id))) throw new Error('DSTS acceptance IDs missing, duplicated or reordered: '+type);
  for(const match of acceptance){
    const published=source.acceptance.find(x=>x.id===match[1]);
    const cells=match[0].split('|').slice(1,-1).map(x=>x.trim());
    if(cells.at(-1)!=='未执行'||cells.at(-2)!==published.requirement) throw new Error('DSTS acceptance state/association changed: '+match[1]);
  }
  for(const entry of source.entries){
    const block=text.split('### '+entry.id+' ')[1]?.split(/^### |^## /m)[0]||'';
    if(!block.includes('#### 1. 页面字段清单')||!block.includes('#### 9. 非功能性需求')) throw new Error('DSTS specification sections missing: '+entry.id);
    for(const label of ['**业务目的**','**操作与规则**','**结果与异常处理**','**开发处理细则**']) if(!block.includes(label)) throw new Error('DSTS business detail missing: '+entry.id+' '+label);
    if((block.match(/^\| [^|]+ \|/gm)||[]).length<CONTROLS[entry.id].length) throw new Error('DSTS control interaction rows missing: '+entry.id);
    for(const image of entry.sources) if(!block.includes(image)) throw new Error('DSTS historical evidence missing: '+entry.id);
  }
  if(type==='main'){
    for(const row of source.sourceRows) if(!text.includes(row)) throw new Error('DSTS source row missing');
    for(const row of source.boundaries) if(!text.includes(row)) throw new Error('DSTS historical boundary missing');
    const nfrSection=text.split(/^## 9\. 非功能需求\s*$/m)[1]||'';
    const nfr=[...nfrSection.matchAll(/^\| (DSTS-NFR-\d{3}) \|.*$/gm)].map(x=>x[1]);
    if(JSON.stringify(nfr)!==JSON.stringify(NFR.map(x=>x[0]))) throw new Error('DSTS NFR IDs missing, duplicated or reordered');
  }
  if(!text.includes('<!-- 业务规格格式:plain-v1 -->')||!text.includes('<!-- dsts:generated-spec-v1 -->')) throw new Error('DSTS generation marker missing');
  if(/【|】|待确认|拟定需求|本轮|源码|历史DOM/.test(text)) throw new Error('DSTS plain specification contains investigation labels');
}
